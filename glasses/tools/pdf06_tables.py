def fix_tables(bank):
    """就地改写 bank["questions"][*][field]，返回改动条数。"""
    by_id = {q["id"]: q for q in bank["questions"]}
    changed = 0
    for qid, field, head, tail, text in RULES:
        q = by_id.get(qid)
        if q is None:
            raise SystemExit(f"找不到题目 {qid}")
        src = q.get(field) or ""
        pat = re.compile(head + r".*?" + tail + r"[ \t]*", re.S)
        if not pat.search(src):
            raise SystemExit(f"{qid}.{field} 里没找到表格锚点：{head} … {tail}")
        # 前后各补一个换行，避免表格与相邻段落粘成一整段
        q[field] = re.sub(r"\n{3,}", "\n\n",
                          pat.sub(lambda m: "\n" + text + "\n", src, count=1)).strip()
        changed += 1
    return changed


